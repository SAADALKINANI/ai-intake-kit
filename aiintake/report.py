"""Render assessments as Markdown and export inventory rows."""

from __future__ import annotations

import csv
from pathlib import Path

from .assess import Assessment
from .policy import PRACTICES, PRESUMED_CATEGORIES, SOURCES

_ICON = {"Done": "✅", "In progress": "🟡", "Waived": "⚪", "Missing": "❌"}


def to_markdown(a: Assessment) -> str:
    i = a.intake
    lines = [f"# AI use case assessment: {i.get('use_case_name', '(unnamed)')}", "",
             f"**Agency / bureau:** {i.get('agency', '')} / {i.get('bureau', '')}  ",
             f"**Stage:** {i.get('development_stage', '')} · **Topic:** {i.get('topic_area', '')} · "
             f"**Type:** {i.get('classification', '')}", ""]
    if a.errors:
        lines += ["## ⛔ Validation errors", ""] + [f"- {e}" for e in a.errors] + [""]
    lines += ["## High-impact determination", "", f"**{a.determination}**", "", a.rationale, ""]
    if a.presumed:
        lines += ["Presumed high-impact categories selected:", ""]
        lines += [f"- {PRESUMED_CATEGORIES[c]['label']}" for c in a.presumed if c in PRESUMED_CATEGORIES] + [""]
    if a.suggested:
        lines += ["Categories suggested by keyword screen (advisory, please confirm):", ""]
        lines += [f"- {PRESUMED_CATEGORIES[c]['label']} (matched: {', '.join(h)})" for c, h in a.suggested.items()] + [""]
    if a.practice_status:
        lines += ["## Minimum risk-management practices", "", "| Practice | M-25-21 | Status |", "|---|---|---|"]
        for k, s in a.practice_status.items():
            lines.append(f"| {PRACTICES[k]['label']} | {PRACTICES[k]['ref']} | {_ICON[s]} {s} |")
        lines.append("")
    lines += ["## Compliance", "", f"**{a.compliance}**", ""]
    if a.warnings:
        lines += ["## Warnings", ""] + [f"- {w}" for w in a.warnings] + [""]
    if a.next_steps:
        lines += ["## Next steps", ""] + [f"{n}. {s}" for n, s in enumerate(a.next_steps, 1)] + [""]
    lines += ["---", "_Generated by ai-intake-kit. This is decision support, not legal advice or an official "
              f"determination. Sources: {SOURCES['M-25-21']}; {SOURCES['2025-guidance']}._"]
    return "\n".join(lines)


#: 2025 inventory columns (individually reported use cases) this tool can fill.
INVENTORY_COLUMNS = ["use_case_name", "agency", "agency_bureau", "contact_email", "development_stage",
                     "is_high_impact", "HI_justification", "topic_area", "classification", "problem_solved",
                     "benefits", "system_outputs", "operational_date", "contracting_usage", "vendor_name",
                     "have_ato", "system_name_ato", "data_description", "has_pii", "pia_url",
                     "demographic_features", "has_custom_code", "code_url"] + \
                    [p["inventory_field"] for p in PRACTICES.values()] + ["hi_potential_impacts"]


def to_inventory_row(a: Assessment) -> dict:
    i, data, role = a.intake, a.intake.get("data") or {}, a.intake.get("decision_role") or {}
    yn = lambda v: "" if v is None else ("Yes" if v else "No")  # noqa: E731
    row = {
        "use_case_name": i.get("use_case_name", ""), "agency": i.get("agency", ""),
        "agency_bureau": i.get("bureau", ""), "contact_email": i.get("contact_email", ""),
        "development_stage": i.get("development_stage", ""),
        "is_high_impact": {"High-impact": "High-impact", "Not high-impact": "Not high-impact"}.get(
            a.determination, "Presumed high-impact, but determined not high-impact"),
        "HI_justification": role.get("not_high_impact_justification", ""),
        "topic_area": i.get("topic_area", ""), "classification": i.get("classification", ""),
        "problem_solved": i.get("problem_solved", ""), "benefits": i.get("benefits", ""),
        "system_outputs": i.get("system_outputs", ""), "operational_date": i.get("operational_date", ""),
        "contracting_usage": i.get("contracting_usage", ""), "vendor_name": i.get("vendor_name", ""),
        "have_ato": yn(i.get("have_ato")), "system_name_ato": i.get("system_name_ato", ""),
        "data_description": data.get("description", ""), "has_pii": yn(data.get("has_pii")),
        "pia_url": data.get("pia_url", ""),
        "demographic_features": "; ".join(data.get("demographic_features") or []),
        "has_custom_code": yn(i.get("has_custom_code")), "code_url": i.get("code_url", ""),
        "hi_potential_impacts": (i.get("practices") or {}).get("potential_impacts", "") if a.is_high_impact else "",
    }
    practices = i.get("practices") or {}
    for key, spec in PRACTICES.items():
        v = practices.get(key, "") if a.is_high_impact else ""
        row[spec["inventory_field"]] = "; ".join(v) if isinstance(v, list) else (v or "")
    return {c: row.get(c, "") for c in INVENTORY_COLUMNS}


def export_inventory(assessments: list[Assessment], path: str | Path) -> Path:
    path = Path(path)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=INVENTORY_COLUMNS)
        w.writeheader()
        for a in assessments:
            w.writerow(to_inventory_row(a))
    return path
